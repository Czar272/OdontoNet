"""Cadena completa de migraciones sobre una base vacía (ODON-210).

Corre en CI (Linux) y localmente, igual que `scripts/dev/verify-infra.ps1`
en Windows: sube hasta la última, baja hasta la base vacía, vuelve a subir y
comprueba que los modelos coinciden con el esquema (alembic check). Usa una
base temporal propia, nunca la de pruebas ni la de desarrollo.
"""
import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from tests.conftest import BACKEND_DIR, TEST_DATABASE_URL

pytestmark = [pytest.mark.migrations]


@pytest.fixture
def empty_database():
    url = make_url(TEST_DATABASE_URL)
    name = f"{url.database}_migrations"
    assert name.endswith("_test_migrations")
    admin = create_engine(url.set(database="postgres"), isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        # WITH (FORCE): una conexión olvidada (pgAdmin, un proceso interrumpido) no bloquea la prueba.
        conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    engine = create_engine(url.set(database=name))
    try:
        yield engine
    finally:
        engine.dispose()
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def _config(connection) -> Config:
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    config.attributes["connection"] = connection
    return config


def test_single_head():
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    assert len(ScriptDirectory.from_config(config).get_heads()) == 1


def test_full_chain_upgrade_downgrade_upgrade(empty_database):
    with empty_database.begin() as conn:
        command.upgrade(_config(conn), "head")
    with empty_database.connect() as conn:
        tables = set(inspect(conn).get_table_names())
    assert {"clinics", "patients", "appointments", "periodontal_exams"} <= tables

    with empty_database.begin() as conn:
        command.downgrade(_config(conn), "base")
    with empty_database.connect() as conn:
        assert set(inspect(conn).get_table_names()) <= {"alembic_version"}

    with empty_database.begin() as conn:
        command.upgrade(_config(conn), "head")
    with empty_database.connect() as conn:
        # Los modelos y el esquema migrado coinciden (falla con AutogenerateDiffsDetected).
        command.check(_config(conn))
